import Foundation

guard CommandLine.arguments.count > 1 else { exit(1) }

let outputPath = CommandLine.arguments[1]
let env = ProcessInfo.processInfo.environment

func require(_ key: String) -> String? {
    guard let value = env[key], !value.isEmpty else { return nil }
    return value
}

guard let clientId     = require("SF_CLIENT_ID"),
      let clientSecret = require("SF_CLIENT_SECRET"),
      let baseDomain   = require("SF_BASE_DOMAIN") else {
    print("""
    error: Salesforce credentials are not set. \
    To run SalesforceDemo tests, set the following environment variables:
        SF_CLIENT_ID     - Salesforce connected app client ID
        SF_CLIENT_SECRET - Salesforce connected app client secret
        SF_BASE_DOMAIN   - Salesforce org domain (e.g. your-org.my.salesforce.com)
    """)
    exit(1)
}

let content = """
// Auto-generated by GenerateTestCredentials plugin — do not commit
enum TestCredentials {
    static let clientId     = "\(clientId)"
    static let clientSecret = "\(clientSecret)"
    static let baseDomain   = "\(baseDomain)"
}
"""

try content.write(toFile: outputPath, atomically: true, encoding: .utf8)
